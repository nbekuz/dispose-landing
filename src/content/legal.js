/** Parse plain legal text into title + sections for rendering. */
export function parseLegal(raw) {
  const lines = raw.trim().split('\n')
  const title = lines[0]?.trim() || 'Document'
  const rest = lines.slice(1).join('\n').trim()
  const blocks = rest.split(/\n\n+/).filter(Boolean)
  const sections = []
  let current = { heading: null, paragraphs: [] }

  for (const block of blocks) {
    const parts = block.split('\n').map((l) => l.trim()).filter(Boolean)
    if (parts.length === 0) continue

    const isBulletList = parts.every((p) => p.startsWith('•'))
    if (isBulletList) {
      current.paragraphs.push({ type: 'list', items: parts.map((p) => p.replace(/^•\s*/, '')) })
      continue
    }

    if (parts.length === 1 && parts[0].length < 80 && !parts[0].endsWith('.')) {
      if (current.heading || current.paragraphs.length) sections.push(current)
      current = { heading: parts[0], paragraphs: [] }
      continue
    }

    current.paragraphs.push({ type: 'text', text: parts.join(' ') })
  }

  if (current.heading || current.paragraphs.length) sections.push(current)
  return { title, sections }
}
